'use strict';

// Builds docs/maquina/, the live machine on the project page (GitHub Pages).
// It copies the real overlay from public/ and loads docs/maquina/replay.js
// first, which plays back docs/maquina/demo.json (a recording of
// "ryoiki demo") in place of the local server.
//
//   node scripts/record-demo.js   # records demo.json again (about 60 s)
//   node scripts/build-page.js    # copies the overlay into docs/maquina/

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
const OUT = path.join(ROOT, 'docs', 'maquina');
const FILES = ['overlay.css', 'overlay.js', 'i18n.js', 'lines.js', 'hand-sign.svg', 'app-icon.png'];

fs.mkdirSync(OUT, { recursive: true });
for (const name of FILES) fs.copyFileSync(path.join(PUBLIC, name), path.join(OUT, name));

let html = fs.readFileSync(path.join(PUBLIC, 'index.html'), 'utf8');
const hook = '<script src="i18n.js"></script>';
if (!html.includes(hook)) throw new Error('public/index.html changed: i18n.js script tag not found');
html = html
  .replace(hook, `<script src="replay.js"></script>\n  ${hook}`)
  .replace('href="icon.png"', 'href="app-icon.png"')
  .replace('<title>Idle Death Gamble</title>', '<title>Zasatsu Bakuto · demo</title>\n  <meta name="robots" content="noindex">');
fs.writeFileSync(path.join(OUT, 'index.html'), '<!-- Generated by scripts/build-page.js from public/index.html. Do not edit. -->\n' + html);
console.log(`docs/maquina: ${FILES.length + 1} files from public/`);
